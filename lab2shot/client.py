TRANSFER_TIMEOUT = 3600.0  # seconds for one file up or down (plates are big)
_TOKEN = re.compile(r"#+|%0?(\d*)d|\$F(\d*)")
# a file's shape: its name with every digit run left out (a minus sign after a dot, an underscore or the start is part
# of the run), the extension kept whole. Frames of one sequence share it. A standard-library copy of
# lab2shot.io.sequence.shape_of (the two must stay equal): which run is the frame number the server decides.
_RUN = re.compile(r"(?<![^._])-\d+(?![\dA-Za-z])|\d+(?![\dA-Za-z])")
_EXT = re.compile(r"\.[A-Za-z0-9]*[A-Za-z][A-Za-z0-9]*$")


def _shape(name):
    ext = _EXT.search(name)
    stem, suffix = (name[:ext.start()], ext.group()) if ext else (name, "")
    pieces = _RUN.split(stem)
    pieces[-1] += suffix
    return "#".join(p.replace("#", "##") for p in pieces)


def _junk(name):
    return name.startswith(".") or name.lower() in ("thumbs.db", "desktop.ini", "icon\r")


class Lab2ShotError(RuntimeError):
    def __init__(self, text, status=None, code=None):
        super(Lab2ShotError, self).__init__(text)
        self.status = status  # the server's answer (0: no answer; None: not about a request)
        self.code = code  # the message's code when the client said it itself (E-CLIENT-...)


